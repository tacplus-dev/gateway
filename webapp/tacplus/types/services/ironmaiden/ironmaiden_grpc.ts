// Package ironmaiden provides protobuf definitions for the Iron Maiden service.
//
// Iron Maiden is the centralized OAuth2 authentication gateway. The auth flow:
//
//   1. User hits a microservice (e.g. fleetwood). The frontend wrapper checks
//      for a valid bearer token. If absent/invalid, redirects to Iron Maiden
//      with a callback_url query parameter.
//
//   2. Iron Maiden's webapp shows provider selection. User picks an IDP.
//      Iron Maiden redirects to the IDP with PKCE, state, and nonce.
//      The nonce/PKCE state is kept in memory on the originating instance.
//
//   3. IDP authenticates the user and redirects back to Iron Maiden's callback.
//      If the callback lands on a different instance, that instance publishes
//      the callback data to the callback_relay topic. The originating instance
//      receives it via subscription, exchanges the authorization code for an
//      ID token, validates it against the IDP's JWKS (cached in elvis),
//      and mints a refresh token signed by Iron Maiden's own keys.
//
//   4. Iron Maiden uses the refresh token to mint a short-lived access token,
//      installs both in the user's browser (cookies), and redirects back to
//      the original callback_url.
//
//   5. Subsequent requests include the access token. When it expires, the
//      frontend wrapper calls Iron Maiden's RefreshToken endpoint using the
//      refresh token to get a new access token without re-authenticating.
//
// Key storage: each Iron Maiden instance generates its own key pair locally,
// keeps the private key in memory, and publishes the public JWK to elvis.
// Cached external IDP JWKS also live in elvis. Other services subscribe
// to Iron Maiden's verifying_keys via Watch (RO) and receive new keys
// immediately — no polling or pre-generation window needed.


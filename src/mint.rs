use std::sync::Arc;

use tonic::transport::Channel;

use gateway_tacplus::types::common::tokenrequest::{TokenMintRequest, X509MintRequest};
use gateway_tacplus::types::libs::jwk::jwk::{Jwks, OpenIdConfiguration};
use gateway_tacplus::types::libs::token::token::Token;
use gateway_tacplus::types::libs::x509::x509::X509CertChain;
use gateway_tacplus::types::services::kernel::kernel::mint_service_client::MintServiceClient;

use crate::auth::GatewayAuth;

/// Gateway MintService implementation.
///
/// OpenIdConfig and Jwks are served locally from watched JWK keys.
/// TokenMint and X509Mint are delegated to kernel via the direct channel.
pub struct GatewayMintService {
    kernel_channel: Channel,
    auth: Arc<GatewayAuth>,
    issuer_url: String,
}

impl GatewayMintService {
    pub fn new(kernel_channel: Channel, auth: Arc<GatewayAuth>, issuer_url: String) -> Self {
        Self {
            kernel_channel,
            auth,
            issuer_url,
        }
    }

    fn build_openid_config(&self) -> OpenIdConfiguration {
        let base = &self.issuer_url;
        OpenIdConfiguration {
            issuer: base.clone(),
            jwks_uri: format!("{}/api/v1/.well-known/jwks.json", base),
            token_endpoint: format!("{}/api/v1/Mint/TokenMint", base),
            subject_types_supported: vec!["public".to_string()],
            id_token_signing_alg_values_supported: vec!["EdDSA".to_string()],
            response_types_supported: vec!["token".to_string()],
            grant_types_supported: vec!["urn:ietf:params:oauth:grant-type:token-exchange".to_string()],
            ..Default::default()
        }
    }

    fn build_jwks(&self) -> Jwks {
        Jwks {
            keys: self.auth.get_raw_jwks(),
        }
    }
}

// The gateway.MintService trait is generated by tacplus from gateway.proto.
// After regen, implement it here. The trait will be at:
//   gateway_tacplus::types::services::gateway::gateway::mint_service_server::MintService
//
// For now, we provide the implementation functions that the generated trait
// methods will call. The actual trait impl is below — it will compile after
// tacplus regen generates the gateway MintService server trait.

#[tonic::async_trait]
impl gateway_tacplus::types::services::gateway::gateway::mint_service_server::MintService
    for GatewayMintService
{
    async fn open_id_config(
        &self,
        _request: tonic::Request<()>,
    ) -> Result<tonic::Response<OpenIdConfiguration>, tonic::Status> {
        Ok(tonic::Response::new(self.build_openid_config()))
    }

    async fn jwks(
        &self,
        _request: tonic::Request<()>,
    ) -> Result<tonic::Response<Jwks>, tonic::Status> {
        Ok(tonic::Response::new(self.build_jwks()))
    }

    async fn token_mint(
        &self,
        request: tonic::Request<TokenMintRequest>,
    ) -> Result<tonic::Response<Token>, tonic::Status> {
        let mut client = MintServiceClient::new(self.kernel_channel.clone());
        client.token_mint(request).await
    }

    async fn x509_mint(
        &self,
        request: tonic::Request<X509MintRequest>,
    ) -> Result<tonic::Response<X509CertChain>, tonic::Status> {
        let mut client = MintServiceClient::new(self.kernel_channel.clone());
        client.x509_mint(request).await
    }
}

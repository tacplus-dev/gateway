use std::sync::Arc;

use gateway_model::s2sm::ServiceManager;
use gateway_model::types::sys::tokenrequest::{TokenMintRequest, TokenMintResponse, X509MintRequest};
use gateway_model::types::sys::jwk::jwk::{Jwks, OpenIdConfiguration};
use gateway_model::types::sys::trace::trace::TraceRequest;
use gateway_model::types::sys::x509::x509::{X509CertChain, X509Cert};
use gateway_model::types::services::gateway::gateway::{PublicCaResponse, mint_server::Mint};

use crate::auth::GatewayAuth;

const ID_TOKEN_SIGNING_ALGS_SUPPORTED: &[&str] = &["EdDSA", "ES256"];

/// Gateway Mint service implementation.
///
/// GetOpenIdConfig and ListJwks are served locally from watched JWK keys.
/// TokenMint and X509Mint are delegated to kernel.Mint — kernel is the cluster
/// trust root and the sole token + cert signing authority
/// (sm.s2s().kernel().mint_client()).
/// ListPublicCa serves the root CA cert(s) from gateway config — the CA that
/// signed the external TLS cert, which clients need to configure TLS trust.
pub struct GatewayMintService {
    sm: Arc<ServiceManager>,
    auth: Arc<GatewayAuth>,
    issuer_url: String,
    root_ca: Vec<X509Cert>,
}

impl GatewayMintService {
    pub fn new(
        sm: Arc<ServiceManager>,
        auth: Arc<GatewayAuth>,
        issuer_url: String,
        root_ca: Vec<X509Cert>,
    ) -> Self {
        Self {
            sm,
            auth,
            issuer_url,
            root_ca,
        }
    }

    fn build_openid_config(&self) -> OpenIdConfiguration {
        let issuer = &self.issuer_url;
        OpenIdConfiguration {
            issuer: issuer.clone(),
            jwks_uri: format!("{}/.well-known/jwks.json", issuer),
            token_endpoint: format!("{}/gateway/TokenMint", issuer),
            subject_types_supported: vec!["public".to_string()],
            id_token_signing_alg_values_supported: ID_TOKEN_SIGNING_ALGS_SUPPORTED.iter().map(|alg| (*alg).to_string()).collect(),
            response_types_supported: vec!["token".to_string()],
            grant_types_supported: vec!["urn:ietf:params:oauth:grant-type:token-exchange".to_string()],
            ..Default::default()
        }
    }

    fn build_jwks(&self) -> Jwks {
        Jwks {
            keys: self.auth.get_raw_jwks(),
        }
    }
}

/// The one answer to `ListPublicCa`: the CA(s) that signed gateway's external
/// TLS cert, as gateway config carries them.
///
/// Shared with `rest_translation`'s REST translation of the same RPC. The two
/// used to answer from different sources — gRPC from config, REST from the
/// kernel `CaState` store of internal cluster signing CAs — so an
/// unauthenticated REST GET returned internal trust material and the wrong
/// answer to the question the proto asks ("the CA clients need to verify TLS
/// to the gateway"). One function, so they cannot drift apart again.
pub fn public_ca_response(root_ca: &[X509Cert]) -> PublicCaResponse {
    PublicCaResponse {
        certs: root_ca.to_vec(),
        ..Default::default()
    }
}

// The gateway.Mint trait is generated by tacplus from gateway.proto.
// The trait is at:
//   gateway_model::types::services::gateway::gateway::mint_server::Mint

#[tonic::async_trait]
impl Mint for GatewayMintService
{
    async fn get_open_id_config(
        &self,
        _request: tonic::Request<TraceRequest>,
    ) -> Result<tonic::Response<OpenIdConfiguration>, tonic::Status> {
        Ok(tonic::Response::new(self.build_openid_config()))
    }

    async fn list_jwks(
        &self,
        _request: tonic::Request<TraceRequest>,
    ) -> Result<tonic::Response<Jwks>, tonic::Status> {
        Ok(tonic::Response::new(self.build_jwks()))
    }

    async fn mint_token(
        &self,
        request: tonic::Request<TokenMintRequest>,
    ) -> Result<tonic::Response<TokenMintResponse>, tonic::Status> {
        // TokenMint is proxied to kernel.Mint (the sole token authority).
        self.sm.s2s().kernel().mint_client().mint_token(request).await
    }

    async fn mint_x509_cert(
        &self,
        request: tonic::Request<X509MintRequest>,
    ) -> Result<tonic::Response<X509CertChain>, tonic::Status> {
        // X509Mint is proxied to kernel.Mint (the sole cert signing authority).
        self.sm.s2s().kernel().mint_client().mint_x509_cert(request).await
    }

    async fn list_public_ca(
        &self,
        _request: tonic::Request<TraceRequest>,
    ) -> Result<tonic::Response<PublicCaResponse>, tonic::Status> {
        Ok(tonic::Response::new(public_ca_response(&self.root_ca)))
    }
}
